import assert from 'node:assert/strict';
import {solarPosition,timeFromSun,weatherFromCode,weatherURL,parseWeather} from '../app/live-weather.ts';
const noon=solarPosition(new Date('2026-03-20T12:08:00Z'),0,0);
assert(noon.altitude>88,'Equatorial equinox sun must be near zenith');
const east=solarPosition(new Date('2026-03-20T06:08:00Z'),0,0),west=solarPosition(new Date('2026-03-20T18:08:00Z'),0,0);
assert(Math.abs(east.azimuth-90)<2&&Math.abs(west.azimuth-270)<2,'Morning east; evening west');
const tokyo=solarPosition(new Date('2026-09-07T12:00:00Z'),35.68,139.69);
assert.equal(timeFromSun(tokyo),'night');
assert(solarPosition(new Date('2026-06-21T00:00:00Z'),78,15).altitude>0,'Polar summer midnight remains daylight');
assert(solarPosition(new Date('2026-12-21T12:00:00Z'),78,15).altitude<0,'Polar winter noon remains below horizon');
assert(solarPosition(new Date('2026-12-21T12:00:00Z'),-33,18).altitude>55,'Southern summer is not northern winter');
assert.equal(weatherFromCode(0),'clear');assert.equal(weatherFromCode(3),'cloudy');
for(const c of [51,53,55,56,57,61,63,65,66,67,80,81,82])assert.equal(weatherFromCode(c),'rain');
for(const c of [71,73,75,77,85,86])assert.equal(weatherFromCode(c),'snow');
for(const c of [45,48])assert.equal(weatherFromCode(c),'fog');
for(const c of [95,96,99])assert.equal(weatherFromCode(c),'storm');
assert.throws(()=>weatherFromCode(999));
const url=new URL(weatherURL({latitude:35.681236,longitude:139.767125,name:'test'}));
assert.equal(url.searchParams.get('latitude'),'35.68');assert.equal(url.searchParams.get('longitude'),'139.77');
assert.equal(url.hostname,'api.open-meteo.com');
const valid={timezone:'Asia/Tokyo',current:{time:1788782400,temperature_2m:22.8,weather_code:53,cloud_cover:92,wind_speed_10m:2.1,wind_direction_10m:329,precipitation:.2}};
assert.equal(parseWeather(valid).timestamp,1788782400000);
assert.throws(()=>parseWeather({...valid,current:{...valid.current,temperature_2m:null}}));
assert.throws(()=>parseWeather({...valid,timezone:'invalid-zone'}));
console.log('Solar orientation, equinox, polar seasons, southern hemisphere, weather codes, precision and API validation passed.');
